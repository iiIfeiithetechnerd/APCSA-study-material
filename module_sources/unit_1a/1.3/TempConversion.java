public class TempConversion
{
    public static void main(String[] args)
    {
        int intTempF = 70;
        
        System.out.println(5.0 / 9 * (intTempF - 32));
        
        System.out.println(5.0 / 9 * (intTempF - 32));
        
        double doubleTempF = 70;
        
        System.out.println(5.0 / 9 * (doubleTempF - 32));
        
        System.out.println((doubleTempF - 32) * 5 / 9);
    }
}